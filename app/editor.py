"""Второй проход «редактор»: отдельный вызов модели переписывает только тексты для клиента.

Основной анализ — длинная задача из 13 разделов, и правила стиля для двух коротких текстов в ней
соблюдаются не всегда (род менеджера, «вчера», рекламные обороты). Редактор получает только черновики,
факты встречи и правила — и делает одну работу: превращает черновик в сообщение живого менеджера.
"""
from . import client_texts, config, llm

GENDER = {
    "f": "Менеджер — женщина: пиши от её лица в женском роде («уточнила», «готова»).",
    "m": "Менеджер — мужчина: пиши от его лица в мужском роде («уточнил», «готов»).",
    None: "Пол менеджера неизвестен: строй фразы без рода («могу прислать», «уточню», «подскажу»), "
          "никаких «готов/готова», «хотел/хотела», «понял/поняла».",
}

TASK = """Ты редактор отдела продаж. Тебе дают черновики двух текстов, которые менеджер отправит клиенту
без правки: сообщение в мессенджер и скрипт следующего звонка. Перепиши их по правилам ниже.

Что можно: менять слова, порядок, длину, убирать лишнее, делать фразы проще и живее.
Чего нельзя: добавлять факты, цифры, обещания, сроки и действия, которых нет в черновиках или в фактах
встречи. Если в черновике есть утверждение, которого нет в фактах встречи, убери его.
Имена: используй только имена из фактов встречи. Если там «имя неизвестно», а в черновике менеджер
представляется по имени, это имя выдумано — убери его и представься так: «это Royal Brick».

Верни только JSON-объект: {"client_message": "...", "call_script": "..."}
Внутри строк — обычный текст с переносами строк \\n, без markdown."""


def polish(texts: dict, report: str, info: dict, meta: dict) -> dict:
    style = config.STYLE_ADDENDUM_PATH.read_text(encoding="utf-8") if config.STYLE_ADDENDUM_PATH.exists() else ""
    system = f"{TASK}\n\n{GENDER.get(info.get('manager_gender'))}\n\n{style}"

    facts = [
        f"Менеджер: {meta.get('manager_name') or info.get('manager_name') or 'имя неизвестно'}",
        f"Клиент: {info.get('client_name') or 'имя неизвестно'}",
        "Карточка встречи:\n" + client_texts.section(report, 1),
        "Резюме для CRM:\n" + texts.get("crm_summary", ""),
    ]
    user = ("ФАКТЫ ВСТРЕЧИ\n\n" + "\n\n".join(facts)
            + "\n\nЧЕРНОВИК СООБЩЕНИЯ КЛИЕНТУ\n\n" + texts.get("client_message", "")
            + "\n\nЧЕРНОВИК СКРИПТА ЗВОНКА\n\n" + texts.get("call_script", ""))
    data = llm.complete_json(system, user, max_tokens=2500)
    return {k: client_texts.humanize(str(data[k])) for k in ("client_message", "call_script")
            if isinstance(data.get(k), str) and data[k].strip()}
